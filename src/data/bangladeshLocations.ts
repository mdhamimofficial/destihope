// All 64 Districts sorted alphabetically (অক্ষর অনুযায়ী সাজানো)
export const ALL_DISTRICTS: string[] = Object.values(DIVISION_DISTRICTS_MAP)
  .flat()
  .sort((a, b) => a.localeCompare(b, 'bn'));

// Map District to Division
export const DISTRICT_TO_DIVISION_MAP: Record<string, string> = {};
Object.entries(DIVISION_DISTRICTS_MAP).forEach(([division, districts]) => {
  districts.forEach(district => {
    DISTRICT_TO_DIVISION_MAP[district] = division;
  });
});

// Alphabetically sorted divisions
export const SORTED_DIVISIONS = [...BANGLADESH_DIVISIONS].sort((a, b) => a.localeCompare(b, 'bn'));

// Distinct Bengali first letters of districts for quick alphabet indexing
export const DISTRICT_ALPHABETS = Array.from(
  new Set(ALL_DISTRICTS.map(d => d.charAt(0)))
).sort((a, b) => a.localeCompare(b, 'bn'));

/**
 * Helper to get districts for a selected division, always sorted alphabetically.
 * If division is 'all' or empty, returns all 64 districts sorted.
 */
export function getDistricts(division?: string): string[] {
  if (!division || division === 'all') {
    return [...ALL_DISTRICTS].sort((a, b) => a.localeCompare(b, 'bn'));
  }
  const districts = DIVISION_DISTRICTS_MAP[division] || ALL_DISTRICTS;
  return [...districts].sort((a, b) => a.localeCompare(b, 'bn'));
}

/**
 * Helper to get upazilas for a selected district, sorted alphabetically.
 * If district is 'all' or empty, returns an empty list.
 */
export function getUpazilas(district?: string): string[] {
  if (!district || district === 'all') {
    return [];
  }
  const upazilas = DISTRICT_UPAZILAS_MAP[district] || [`${district} সদর`];
  return [...upazilas].sort((a, b) => a.localeCompare(b, 'bn'));
}

/**
 * Helper to get division name from district.
 */
export function getDivisionOfDistrict(district: string): string | undefined {
  return DISTRICT_TO_DIVISION_MAP[district];
}

export interface LocationSearchResult {
  type: 'district' | 'upazila';
  name: string;
  district: string;
  division: string;
  upazila?: string;
}

/**
 * Fast search helper across all 64 districts and upazilas.
 */
export function searchLocations(query: string, maxResults = 12): LocationSearchResult[] {
  if (!query || !query.trim()) return [];
  const q = query.trim().toLowerCase();
  const results: LocationSearchResult[] = [];

  // Search districts first
  for (const dist of ALL_DISTRICTS) {
    if (dist.toLowerCase().includes(q)) {
      results.push({
        type: 'district',
        name: dist,
        district: dist,
        division: DISTRICT_TO_DIVISION_MAP[dist] || ''
      });
    }
  }

  // Search upazilas
  for (const [dist, upzList] of Object.entries(DISTRICT_UPAZILAS_MAP)) {
    for (const upz of upzList) {
      if (upz.toLowerCase().includes(q)) {
        // avoid duplicate if upz matches district exactly
        if (upz === dist) continue;
        results.push({
          type: 'upazila',
          name: upz,
          district: dist,
          division: DISTRICT_TO_DIVISION_MAP[dist] || '',
          upazila: upz
        });
        if (results.length >= maxResults * 2) break;
      }
    }
  }

  return results.slice(0, maxResults);
}

